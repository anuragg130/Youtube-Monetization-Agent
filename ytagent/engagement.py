"""Audience engagement metrics derived from per-video statistics."""
from typing import Iterable, List, Mapping, Tuple


def engagement_rate(likes: int, comments: int, views: int) -> float:
    """Return (likes + comments) as a percentage of ``views``.

    Returns 0.0 when there are no views.

    Raises:
        ValueError: if any count is negative.
    """
    if likes < 0 or comments < 0 or views < 0:
        raise ValueError("likes, comments and views must be non-negative")
    if views == 0:
        return 0.0
    return round((likes + comments) / views * 100, 2)


def subscriber_conversion_rate(new_subscribers: int, views: int) -> float:
    """Return new subscribers gained per 1,000 views.

    Useful alongside :func:`ytagent.progress.days_to_eligibility` to judge
    how efficiently views turn into subscribers. Returns 0.0 with no views.
    """
    if new_subscribers < 0 or views < 0:
        raise ValueError("new_subscribers and views must be non-negative")
    if views == 0:
        return 0.0
    return round(new_subscribers / views * 1000, 2)


def comments_per_thousand_views(comments: int, views: int) -> float:
    """Return comments received per 1,000 views.

    Comments signal deeper engagement than likes, so tracking them apart
    from :func:`engagement_rate` shows whether videos spark discussion.
    Returns 0.0 when there are no views.

    Raises:
        ValueError: if either count is negative.
    """
    if comments < 0 or views < 0:
        raise ValueError("comments and views must be non-negative")
    if views == 0:
        return 0.0
    return round(comments / views * 1000, 2)


def watch_hours_from_views(views: int, avg_view_duration_minutes: float) -> float:
    """Return total watch hours generated by ``views`` at an average duration.

    Handy for projecting progress toward the 4,000 public watch-hour YPP
    threshold from expected view counts.

    Raises:
        ValueError: if views or the average duration is negative.
    """
    if views < 0 or avg_view_duration_minutes < 0:
        raise ValueError("views and avg_view_duration_minutes must be non-negative")
    return round(views * avg_view_duration_minutes / 60, 2)


def channel_engagement_rate(videos: Iterable[Mapping[str, int]]) -> float:
    """Return the view-weighted engagement rate across several videos.

    Each item needs ``likes``, ``comments`` and ``views`` keys. Totals are
    summed before dividing, so a single low-view video cannot skew the
    result the way averaging per-video :func:`engagement_rate` values would.

    Raises:
        KeyError: if a video is missing one of the required keys.
        ValueError: if any count is negative.
    """
    likes = comments = views = 0
    for index, video in enumerate(videos):
        counts = (video["likes"], video["comments"], video["views"])
        if min(counts) < 0:
            raise ValueError(f"video {index} has a negative count")
        likes += counts[0]
        comments += counts[1]
        views += counts[2]
    return engagement_rate(likes, comments, views)


def average_percentage_viewed(avg_view_duration_seconds: float, video_length_seconds: float) -> float:
    """Return how much of a video the average viewer watched, as a percentage.

    This mirrors YouTube Studio's "average percentage viewed" retention metric.
    Rewatches can push the raw ratio above 100%, so the result is capped there.

    Raises:
        ValueError: if the duration is negative or the video length is not positive.
    """
    if avg_view_duration_seconds < 0:
        raise ValueError("avg_view_duration_seconds must be non-negative")
    if video_length_seconds <= 0:
        raise ValueError("video_length_seconds must be positive")
    return round(min(100.0, avg_view_duration_seconds / video_length_seconds * 100), 1)


def top_videos_by_engagement(videos: Iterable[Mapping[str, object]], n: int = 3) -> List[Tuple[str, float]]:
    """Return the ``n`` most engaging videos as ``(title, engagement_rate)`` pairs.

    Each item needs ``title``, ``likes``, ``comments`` and ``views`` keys.
    Rates come from :func:`engagement_rate`; ties keep their input order.
    Videos with no views score 0.0 rather than being dropped.

    Raises:
        ValueError: if ``n`` is less than 1 or any count is negative.
        KeyError: if a video is missing a required key.
    """
    if n < 1:
        raise ValueError("n must be at least 1")
    scored = [
        (str(video["title"]), engagement_rate(video["likes"], video["comments"], video["views"]))
        for video in videos
    ]
    return sorted(scored, key=lambda item: item[1], reverse=True)[:n]


def underperforming_videos(
    videos: Iterable[Mapping[str, object]], threshold: float = 0.5
) -> List[Tuple[str, float]]:
    """Return videos whose engagement rate is below ``threshold`` x the channel rate.

    The channel baseline comes from :func:`channel_engagement_rate`, so a
    ``threshold`` of 0.5 flags videos engaging at less than half the
    channel's view-weighted average. Videos with no views are skipped, and
    results are ``(title, engagement_rate)`` pairs sorted lowest first.

    Raises:
        ValueError: if ``threshold`` is negative or any count is negative.
        KeyError: if a video is missing a required key.
    """
    if threshold < 0:
        raise ValueError("threshold must be non-negative")
    videos = list(videos)
    cutoff = channel_engagement_rate(videos) * threshold
    flagged = [
        (str(video["title"]), engagement_rate(video["likes"], video["comments"], video["views"]))
        for video in videos
        if video["views"] > 0
    ]
    return sorted((item for item in flagged if item[1] < cutoff), key=lambda item: item[1])
